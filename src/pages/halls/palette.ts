// أصفر ولا برتقالي، جواب المالك عن معنى اللون الأحمر في المعمل). مفحوصة بمدقّق الألوان لكلّ الأزواج (لقاحان أو أكثر في يوم واحد) في الوضعين:
// الفاتح على #ffffff والداكن على #101827 — الحدّ الأدنى للتمييز بالنظر العادي 15.1، وبعمى الألوان 6.7 (حلال مع ترميز ثانٍ: اسم اللقاح
// مكتوب دائماً بجانب لونه بحبر النصّ، لا بلون اللقاح)، و#0369a1 دون 3:1 على الداكن فالاسم المكتوب هو العلاج. الدرجات نفسها في الوضعين.
export const VACCINE_PALETTE: readonly string[] = ['#6180fe', '#0369a1', '#8832fd', '#c6099f', '#a0522d'];
export const VACCINE_OTHER = '#7c8798';

export function vaccineColor(slot: number): string {
  return slot >= 0 && slot < VACCINE_PALETTE.length ? (VACCINE_PALETTE[slot] ?? VACCINE_OTHER) : VACCINE_OTHER;
}

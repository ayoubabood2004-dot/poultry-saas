// money.ts: حالات الحافة من قواعد الحساب والمثال المحسوب بـdocs/FOUNDATION.md، بالفلس وبلا تسامح.
// الوحدات: الكمية بالآلاف (غرام)، والقيمة بالفلس (١/١٠٠ دينار).
import { loadSrc } from './load-src.mjs';

export default async function (t) {
  const m = await loadSrc('src/domain/money.ts');

  t.eq(m.roundHalfAway(5n, 2n), 3n, 'نصف موجب بعيداً عن الصفر');
  t.eq(m.roundHalfAway(-5n, 2n), -3n, 'نصف سالب بعيداً عن الصفر');
  t.eq(m.roundHalfAway(4n, 3n), 1n, '1.33 ← 1');
  t.eq(m.roundHalfAway(-1n, 3n), 0n, '−0.33 ← 0');
  t.throws(() => m.roundHalfAway(1n, 0n), 'قسمة على صفر ترفض');

  // حالات الحافة المكتوبة بقاعدة 8: التقريب المزدوج يطلّع .01 ودينار زايد.
  t.eq(m.mulDivRound2(99_999_999n, 40_000_000_001n, 200_000_000n), 19_999_999_800n, 'سحب 99,999.999 من 200,000 بقيمة 400,000,000.01 ← 199,999,998.00');
  t.eq(m.mulDivRound0(99_999_999n, 40_000_000_100n, 200_000_000n), 19_999_999_800n, '_mul_div_round0 ← 199,999,998 دينار');
  t.eq(m.mulDivRound2(1_000n, -3n, 2_000n), -2n, '_mul_div_round2(1, −0.03, 2) ← −0.02');
  t.eq(m.mulDivRound2(500_000n, -12_000_000n, 3_000_000n), -2_000_000n, '_mul_div_round2(500, −120,000.00, 3,000) ← −20,000.00');
  t.throws(() => m.mulDivRound2(0n, 1n, 1n), 'q صفر يرفض');
  t.throws(() => m.mulDivRound2(1n, 1n, 0n), 'l صفر يرفض');

  // المثال المحسوب: سحوبات الدفعات.
  t.eq(m.mulDivRound2(2_120_000n, 240_416_667n, 5_000_000n), 101_936_667n, 'سحب C2: 2,120 كغم ← 1,019,366.67');
  t.eq(m.mulDivRound2(40_000n, 80_000_000n, 1_000_000n), 3_200_000n, 'P1 تسحب 40 لتر من مرآة DS1 ← 32,000.00');
  t.eq(m.mulDivRound2(250_000n, 230_000_000n, 1_000_000n), 57_500_000n, 'زيت P1: 250 لتر ← 575,000.00');
  t.eq(m.mulDivRound2(5_000_000n, 691_106_667n, 9_950_000n), 347_289_782n, 'T1: 5,000 كغم من F1 ← 3,472,897.82');
  t.eq(m.mulDivRound2(3_000_000n, 347_289_782n, 5_000_000n), 208_373_869n, 'I1: 3,000 كغم لـBF1 ← 2,083,738.69');
  t.eq(m.mulDivRound2(500_000n, 208_373_869n, 3_000_000n), 34_728_978n, 'إرجاع 500 كغم من BF1 ← 347,289.78');
  t.eq(m.mulDivRound2(28_000_000n, 900_000_000n, 30_000_000n), 840_000_000n, 'إدخال B1: 28,000 بيضة ← 8,400,000.00');
  t.eq(m.mulDivRound2(24_000n, 60_000_000n, 30_000n), 48_000_000n, 'لقاح B1: 24 قنينة ← 480,000.00');
  t.eq(m.mulDivRound2(15_000_000n, 935_000_000n, 23_500_000n), 596_808_511n, 'كلفة CH-2026-0001: 15,000 فرخ ← 5,968,085.11');
  t.eq(m.mulDivRound2(1_000_000n, 60_000_000n, 2_000_000n), 30_000_000n, 'كلفة HE-2026-0001 ← 300,000.00');

  // مبالغ السطور بالدينار الصحيح.
  t.eq(m.lineAmount(9_054_500n, 275_000n), 2_489_987_500n, 'تذكرة الوزن: 9,054.500 كغم × 2,750 ← 24,899,875');
  t.eq(m.lineAmount(99_000n, 4_000_000n), 396_000_000n, 'INV1: 99 كيس × 40,000 ← 3,960,000');
  t.eq(m.lineAmount(250_000n, 500_000n), 125_000_000n, 'EG-2026-0001: 250 طبقة × 5,000 ← 1,250,000');
  t.eq(m.lineAmount(1_500n, 33_333n), 50_000n, '1.5 × 333.33 = 499.995 ← 500 دينار صحيح');
  t.ok(m.isWholeDinar(m.lineAmount(1_234n, 98_765n)), 'مبلغ السطر دائماً دينار صحيح');

  t.eq(m.roundToDinar(150n), 200n, '1.50 ← 2');
  t.eq(m.roundToDinar(149n), 100n, '1.49 ← 1');
  t.eq(m.roundToDinar(-150n), -200n, '−1.50 ← −2');

  t.eq(m.parseMoney('1,234.56'), 123_456n, 'فواصل الآلاف');
  t.eq(m.parseMoney('١٬٢٣٤٫٥'), 123_450n, 'أرقام شرقية و«٫»');
  t.eq(m.parseMoney('2.500'), 250n, 'أصفار زايدة مقبولة');
  t.eq(m.parseMoney('-0.5'), -50n, 'سالب');
  t.eq(m.parseMoney('1.234'), null, 'ثلاث مراتب ترفض');
  t.eq(m.parseMoney(''), null, 'فارغ يرفض');
  t.eq(m.parseMoney('abc'), null, 'حروف ترفض');

  // الفاصلة بس كفاصلة آلاف صحيحة: «2,50» كانت تنقرا 250.00 دينار عن 2.50.
  t.eq(m.parseMoney('6,120'), 612_000n, 'مجموعة آلاف وحدة');
  t.eq(m.parseMoney(' 12.5 '), 1_250n, 'فراغ بالطرفين ينشال');
  t.eq(m.parseMoney('-1,234,567.25'), -123_456_725n, 'سالب بمجموعات');
  for (const text of ['0,5', '2,50', ',5', '1,2,3', '1 5', '٠٬٥', '0,500', '12,34', '1234,567', '1,234,', '1, 234']) {
    t.eq(m.parseMoney(text), null, `«${text}» ترفض: فاصلة أو فراغ بغير مكانه`);
  }
}

// مفتاح توائم الجهات (خطّة المرحلة 1 E34): الموبايل العراقي موحّداً، وغيره أرقامه الغربية بس. نفس الحالات تنقارن ويّا
// private.phone_key بحزمة بوستغريس (parity.test)، ويّا PHONE_CASES كلها.
export const PHONE_KEY_CASES = [
  ['07701234567', '9647701234567'],
  ['+964 770 123 4567', '9647701234567'],
  ['٠٧٧٠ ١٢٣ ٤٥٦٧', '9647701234567'],
  ['07٧٠12٣4567', '9647701234567'],
  // أرضي عراقي (بغداد 01، أربيل 066): مو موبايل، فأرقامه كما انكتبت، والشكلان ما يتوحّدان (E34 حرفياً).
  ['01 718 1234', '017181234'],
  ['(066) 222-3344', '0662223344'],
  ['+964 1 718 1234', '96417181234'],
  ['٠١ ٧١٨ ١٢٣٤', '017181234'],
  // أجنبي: الأرقام كما انكتبت، و00 تبقى (المفتاح من النصّ، مو من الشكل المقصوص).
  ['+1 202 555 0100', '12025550100'],
  ['0044 20 7946 0958', '00442079460958'],
  // موبايل مكسور: ما يصير موحّداً، فأرقامه بس.
  ['0770٬123٬4567', '07701234567'],
  ['0770 12a 4567', '0770124567'],
  ['0770\u{200B}1234567', '07701234567'],
  ['0770123456', '0770123456'],
  // بلا رقم: null، مو نصّ فارغ يطابق كل جهة بلا هاتف.
  ['', null],
  ['abc', null],
  ['+', null],
  ['--- ()', null],
  ['٫٬', null],
];

export default async function (t) {
  const p = await loadSrc('src/domain/phone.ts');
  for (const [input, expected] of PHONE_CASES) t.eq(p.normalizePhone(input), expected, `«${input}»`);
  for (const [input, expected] of PHONE_KEY_CASES) t.eq(p.phoneKey(input), expected, `phoneKey «${input}»`);
  // كل موبايل موحّد مفتاحه نفسه، وكل اللي ما توحّد مفتاحه أرقامه أو null.
  for (const [input, normalized] of PHONE_CASES) {
    const key = p.phoneKey(input);
    if (normalized) t.eq(key, normalized, `phoneKey للموبايل «${input}» = شكله الموحّد`);
    else t.ok(key === null || /^[0-9]+$/.test(key), `phoneKey لغير الموبايل «${input}» أرقام بس أو null (${key})`);
  }
  // بريد الدخول: الشكل الموحّد بس، والغلط ما يبني بريداً.
  t.eq(p.loginEmail('0770 123 4567'), '9647701234567@phone.login', 'بريد الدخول من الرقم الموحّد');
  t.eq(p.loginEmail('٠٧٧٠١٢٣٤٥٦٧'), '9647701234567@phone.login', 'بريد الدخول من الأرقام الشرقية');
  t.eq(p.loginEmail('12345'), null, 'رقم غلط ما يبني بريداً');
  t.eq(p.PHONE_LOGIN_DOMAIN, 'phone.login', 'نطاق الدخول');
}

// naturalOrder.ts: ترتيب الأسماء بأرقامها (شاشة الزبون 2026-11-15: «قاعة 44» قبل «قاعة 5» بترتيب القاعدة حرفاً حرفاً).
import { loadSrc } from './load-src.mjs';

export default async function (t) {
  const n = await loadSrc('src/domain/naturalOrder.ts');
  const sorted = (names) => [...names].sort(n.naturalCompare);

  t.same(sorted(['قاعة 1', 'قاعة 4', 'قاعة 44', 'قاعة 5', 'قاعة 6', 'قاعة 7']), ['قاعة 1', 'قاعة 4', 'قاعة 5', 'قاعة 6', 'قاعة 7', 'قاعة 44'], 'شاشة الزبون: «قاعة 44» بعد «قاعة 7»');
  t.same(sorted(['قاعة 10', 'قاعة 2', 'قاعة 1']), ['قاعة 1', 'قاعة 2', 'قاعة 10'], 'العشرة بعد الاثنين');
  t.same(sorted(['ب', 'أ', 'قاعة 3']), ['أ', 'ب', 'قاعة 3'], 'بلا أرقام: ترتيب نقطة الشفرة كالقاعدة');
  t.same(sorted(['قاعة 05', 'قاعة 5', 'قاعة 4']), ['قاعة 4', 'قاعة 5', 'قاعة 05'], 'الرقم بقيمته، وبالقيمة نفسها الأقلّ أصفاراً أوّلاً');
  t.same(sorted(['قاعة 2 ب', 'قاعة 2 أ', 'قاعة 2']), ['قاعة 2', 'قاعة 2 أ', 'قاعة 2 ب'], 'بعد الرقم نفسه: الاسم الأقصر ثمّ الحروف');
  t.same(sorted(['قاعة 123456789012345678901', 'قاعة 99']), ['قاعة 99', 'قاعة 123456789012345678901'], 'رقم أطول من حدّ الأعداد يُقارن بطوله');
  t.eq(n.naturalCompare('قاعة 7', 'قاعة 7'), 0, 'الاسم نفسه متساوٍ');
}
